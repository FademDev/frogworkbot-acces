const DESCRIPTION_LIMIT = 3000;
const MESSAGE_EMBED_LIMIT = 5;
const MESSAGE_CHAR_LIMIT = 4500;




function renderClause(sectionId, index, clause) {
  const id = `${sectionId}.${index + 1}`;
  const body = Array.isArray(clause.text) ? clause.text.join('\n') : clause.text;
  return `**${id}. ${clause.title}**\n${body}`;
}

function splitIntoChunks(blocks) {
  const chunks = [];
  let current = '';
  for (const block of blocks) {
    const candidate = current ? `${current}\n\n${block}` : block;
    if (current && candidate.length > DESCRIPTION_LIMIT) {
      chunks.push(current);
      current = block;
    } else {
      current = candidate;
    }
  }
  if (current) chunks.push(current);
  return chunks;
}

// Возвращает готовый набор embeds с правилами (без учёта лимита в 10 на сообщение).
function buildRulesEmbeds() {
  const embeds = RULES.flatMap(section => {
    const blocks = section.clauses.map((clause, index) => renderClause(section.id, index, clause));
    const chunks = splitIntoChunks(blocks);
    return chunks.map((description, index) => {
      const part = chunks.length > 1 ? ` (часть ${index + 1} из ${chunks.length})` : '';
      return { section: section.id, name: section.name, description,
        title: `${section.emoji} ${section.id}. ${section.name}${part}`, color: section.color };
    });
  });
  return embeds;
}

// Группирует embeds в сообщения с учётом лимитов Discord (10 embeds / 6000 символов).
function groupIntoMessages(embeds) {
  const messages = [];
  let current = [];
  let size = 0;
  for (const item of embeds) {
    const length = item.title.length + item.description.length;
    const tooMany = current.length >= MESSAGE_EMBED_LIMIT;
    const tooLong = current.length > 0 && size + length > MESSAGE_CHAR_LIMIT;
    if (tooMany || tooLong) {
      messages.push(current);
      current = [];
      size = 0;
    }
    current.push(item);
    size += length;
  }
  if (current.length) messages.push(current);
  return messages;
}

// Готовые сообщения: каждый элемент - набор embeds, помещающийся в одно сообщение.
function buildRulesMessages() {
  return groupIntoMessages(buildRulesEmbeds());
}

